CREATE TABLE IF NOT EXISTS notes_logs (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    source_short VARCHAR(255) NULL DEFAULT NULL,
    source_full TEXT NULL DEFAULT NULL,
    book_id INT UNSIGNED NULL DEFAULT NULL,
    book_title VARCHAR(255) NULL DEFAULT NULL,
    book_slug VARCHAR(255) NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_notes_logs_book_id (book_id)
);